def style_run(r, bold=False, size=SIZE, cn=FONT_CN, en=FONT_EN):
    r.font.name = en
    r.font.size = size
    r.bold = bold
    rPr = r._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), en)
    rFonts.set(qn("w:hAnsi"), en)
    rFonts.set(qn("w:eastAsia"), cn)


def fmt_par(p, indent=True, align=None, line=LINE, before=0, after=0):
    pf = p.paragraph_format
    pf.line_spacing = line
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.first_line_indent = INDENT if indent else None
    if align is not None:
        p.alignment = align


def add_par(cell, text, indent=True, bold=False, align=None, size=SIZE):
    p = cell.add_paragraph()
    fmt_par(p, indent=indent, align=align)
    r = p.add_run(text)
    style_run(r, bold=bold, size=size)
    return p


def add_caption(cell, text):
    p = cell.add_paragraph()
    fmt_par(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER, line=Pt(18), before=6, after=3)
    r = p.add_run(text)
    style_run(r, bold=False, size=Pt(10.5))
    return p


def add_image(cell, path, width_cm):
    p = cell.add_paragraph()
    fmt_par(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER, line=None, before=6, after=3)
    p.paragraph_format.line_spacing = 1.0
    r = p.add_run()
    r.add_picture(path, width=Cm(width_cm))
    return p


def _build_tblPr(tbl, widths_cm):
    """按 OOXML 规定顺序重建 tblPr，避免 LibreOffice 忽略 fixed 布局而撑宽表格。"""
    old = tbl._tbl.tblPr
    new = OxmlElement("w:tblPr")
    style = old.find(qn("w:tblStyle"))
    if style is not None:
        new.append(style)

    tblW = OxmlElement("w:tblW")
    tblW.set(qn("w:w"), str(int(sum(widths_cm) * 567)))
    tblW.set(qn("w:type"), "dxa")
    new.append(tblW)

    jc = OxmlElement("w:jc")
    jc.set(qn("w:val"), "center")
    new.append(jc)

    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "6")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        borders.append(el)
    new.append(borders)

    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    new.append(layout)

    cellmar = OxmlElement("w:tblCellMar")
    for side, w in (("top", "0"), ("left", "45"), ("bottom", "0"), ("right", "45")):
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:w"), w)
        el.set(qn("w:type"), "dxa")
        cellmar.append(el)
    new.append(cellmar)

    look = OxmlElement("w:tblLook")
    look.set(qn("w:val"), "04A0")
    look.set(qn("w:firstRow"), "1")
    look.set(qn("w:lastRow"), "0")
    look.set(qn("w:firstColumn"), "0")
    look.set(qn("w:lastColumn"), "0")
    look.set(qn("w:noHBand"), "0")
    look.set(qn("w:noVBand"), "1")
    new.append(look)

    tbl._tbl.replace(old, new)


def add_table(cell, header, rows, widths_cm, font_size=Pt(9)):
    tbl = cell.add_table(rows=1 + len(rows), cols=len(header))
    _build_tblPr(tbl, widths_cm)

    for i, gc in enumerate(tbl._tbl.tblGrid.findall(qn("w:gridCol"))):
        gc.set(qn("w:w"), str(int(widths_cm[i] * 567)))

    trPr = tbl.rows[0]._tr.get_or_add_trPr()
    trPr.append(OxmlElement("w:tblHeader"))

    for ri, data in enumerate([header] + rows):
        is_head = ri == 0
        for ci, val in enumerate(data):
            c = tbl.cell(ri, ci)
            c.width = Cm(widths_cm[ci])
            align = WD_ALIGN_PARAGRAPH.CENTER if (is_head or ci in (1, 2, 3, 4)) else WD_ALIGN_PARAGRAPH.LEFT
            p = c.paragraphs[0]
            fmt_par(p, indent=False, align=align, line=Pt(13), before=1, after=1)
            r = p.add_run(str(val))
            style_run(r, bold=is_head, size=font_size)
    return tbl


def clear_cell(cell):
    cell.text = ""
    p = cell.paragraphs[0]
    fmt_par(p, indent=False)
    return p


def find_cell(table, text):
    for row in table.rows:
        for cell in row.cells:
            if cell.text.strip() == text:
                return cell
    raise KeyError(text)


def replace_cell_text(cell, text):
    p = cell.paragraphs[0]
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    r = p.add_run(text)
    style_run(r)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER


def insert_row_after(table, tr, count):
    """以 tr 为模板深拷贝插入 count 行，返回最后插入的 tr。"""
    anchor = tr
    for _ in range(count):
        new_tr = copy.deepcopy(tr)
        anchor.addnext(new_tr)
        anchor = new_tr
    return anchor


def render_blocks(cell, blocks):
    for item in blocks:
        kind = item[0]
        if kind == "h2":
            add_par(cell, item[1], indent=False)
        elif kind == "p":
            add_par(cell, item[1])
        elif kind == "cap":
            add_caption(cell, item[1])
        elif kind == "img":
            add_image(cell, item[1], item[3])
            add_caption(cell, item[2])
        elif kind == "tbl":
            add_table(cell, item[1], item[2], [4.0, 2.6, 1.7, 1.7, 1.7, 4.2])
        elif kind == "tbl4":
            add_table(cell, item[1], item[2], [3.0, 5.6, 2.4, 4.9])


